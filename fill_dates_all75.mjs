// ─────────────── 메인 실행 ───────────────
async function run() {
  let ok = 0, skip = 0, fail = 0;
  const results = [];

  for (const entry of UPDATES) {
    const datesJson = JSON.stringify(entry.dates);
    for (const id of entry.ids) {
      try {
        if (entry.permit === null && entry.dates.length === 0) {
          // 섹션 헤더 or 종전 기준 - permit만 체크
          const r = await sql`
            UPDATE inspection_base_items
            SET standard_dates = ${datesJson}
            WHERE item_id = ${id}
              AND (standard_dates IS NULL OR standard_dates::text = '[]')
            RETURNING item_id`;
          if (r.length > 0) { ok++; results.push(`✅ ${id} (dates 초기화)`); }
          else { skip++; }
        } else if (entry.permit === null) {
          const r = await sql`
            UPDATE inspection_base_items
            SET standard_dates = ${datesJson}
            WHERE item_id = ${id}
              AND (standard_dates IS NULL OR standard_dates::text = '[]')
            RETURNING item_id`;
          if (r.length > 0) { ok++; results.push(`✅ ${id} (종전 dates 추가)`); }
          else { skip++; }
        } else {
          const r = await sql`
            UPDATE inspection_base_items
            SET
              permit_effective_date = ${entry.permit},
              standard_dates        = ${datesJson}
            WHERE item_id = ${id}
              AND (permit_effective_date IS NULL OR standard_dates IS NULL OR standard_dates::text = '[]')
            RETURNING item_id`;
          if (r.length > 0) { ok++; results.push(`✅ ${id} (${entry.permit})`); }
          else { skip++; results.push(`⏭  ${id} (이미 있음)`); }
        }
      } catch(e) {
        fail++;
        results.push(`❌ ${id}: ${e.message}`);
      }
    }
  }

  results.forEach(r => console.log(r));
  console.log(`\n${"═".repeat(60)}`);
  console.log(`✅ 업데이트: ${ok}개 | ⏭ SKIP: ${skip}개 | ❌ 오류: ${fail}개`);

  // 아직 남은 항목 확인
  const remaining = await sql`
    SELECT item_id, section_title FROM inspection_base_items
    WHERE (permit_effective_date IS NULL OR standard_dates IS NULL OR standard_dates::text = '[]')
    ORDER BY sort_order`;
  if (remaining.length > 0) {
    console.log(`\n📝 아직 비어있는 항목 (${remaining.length}개):`);
    remaining.forEach(r => console.log(`  → ${r.item_id} | ${r.section_title}`));
  } else {
    console.log(`\n🎉 모든 항목이 완료되었습니다!`);
  }
}

run().catch(console.error);
