let ok=0, skip=0, revOk=0;

for(const item of ITEMS){
  try {
    const r = await sql`
      INSERT INTO inspection_item_edits
        (item_id, text, effective_date, permit_effective_date, introduction_type,
         standard_note, standard_dates, equipment_types)
      VALUES (
        ${item.item_id}, ${item.text}, ${item.effective_date}, ${item.permit_effective_date},
        ${item.intro}, ${item.note}, ${JSON.stringify(item.sd)}, ${item.eq}
      )
      ON CONFLICT (item_id) DO NOTHING
      RETURNING item_id`;
    if(r.length>0){ console.log(`✅ ${item.item_id}`); ok++; }
    else { console.log(`⏭  ${item.item_id} (SKIP)`); skip++; }
  } catch(e){ console.log(`❌ ${item.item_id}: ${e.message}`); }

  for(const rev of item.revs){
    try {
      await sql`
        INSERT INTO inspection_item_revisions
          (item_id,revision_date,description,effective_date,expiry_date,introduction_type)
        VALUES(${item.item_id},${rev.date},${rev.desc},${rev.date},${rev.expiry},${"revision"})
        ON CONFLICT DO NOTHING`;
      revOk++;
    } catch{}
  }
}

