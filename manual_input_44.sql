14.2.2 및 15.4.4에 적합한 정지장치는 풀리실 내부의 출입문 가까운 곳에 설치되어야 한다.

6.7.1.6 온도
풀리실에 서리가 끼고 물방울이 맺힐 위험이 있다면 설비를 보호할 수 있는 조치가 구비되어야 한다.
풀리실에 전기설비가 포함된 경우, 주위 온도는 기계실의 온도와 비슷해야 한다.

