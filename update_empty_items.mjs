/* ─────────────────────────────────────────────
   ▶ STEP 2: 실제 DB에서 비어있는 항목 찾아 UPDATE
     에이전트5(통합) 수행
───────────────────────────────────────────── */
async function run() {
  // ① 현재 상태 출력
  const emptyRows = await printCurrentState();
  
  if (emptyRows.length === 0) {
    console.log("\n✅ 비어있는 항목이 없습니다!");
    return;
  }

  console.log("\n🔧 빈 항목 채우기 시작...\n");

  // ② 각 빈 항목에 대해 FILL_DATA 매핑
  let updated = 0, skipped = 0;

  // 모든 빈 항목 조회
  const rows = await sql`
    SELECT item_id, section_id, section_title, sort_order
    FROM inspection_base_items
    WHERE text IS NULL OR text = ''
    ORDER BY sort_order
  `;

  for (const row of rows) {
    const title = (row.section_title || "").toLowerCase();
    const sectionId = (row.section_id || "");

    // FILL_DATA에서 매칭되는 항목 찾기
    const match = FILL_DATA.find(fd => {
      const titleMatch = fd.match.section_title_contains 
        ? title.includes(fd.match.section_title_contains.toLowerCase())
        : true;
      const idMatch = fd.match.section_id_like
        ? sectionId.startsWith(fd.match.section_id_like.replace('%', ''))
        : true;
      return titleMatch && idMatch;
    });

    if (match) {
      await sql`
        UPDATE inspection_base_items
        SET 
          text = ${match.text},
          permit_effective_date = ${match.permit_effective_date},
          standard_dates = ${match.standard_dates}
        WHERE item_id = ${row.item_id}
          AND (text IS NULL OR text = '')
      `;
      console.log(`✅ 업데이트: ${row.item_id} | ${row.section_title?.substring(0, 35)}`);
      updated++;
    } else {
      console.log(`⚠️  미매칭: ${row.item_id} | ${row.section_title?.substring(0, 35)} → 수동 확인 필요`);
      skipped++;
    }
  }

  console.log(`\n${"━".repeat(60)}`);
  console.log(`✅ 완료: ${updated}개 업데이트 | ⚠️  ${skipped}개 수동 확인 필요`);
  
  // ③ 미매칭 항목 상세 출력
  if (skipped > 0) {
    console.log("\n📝 수동 입력이 필요한 항목 목록:");
    const stillEmpty = await sql`
      SELECT item_id, section_id, section_title 
      FROM inspection_base_items
      WHERE text IS NULL OR text = ''
      ORDER BY sort_order
    `;
    stillEmpty.forEach(r => 
      console.log(`  → ${r.item_id} | ${r.section_id} | ${r.section_title}`)
    );
  }
}

run().catch(console.error);
